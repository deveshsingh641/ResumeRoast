import React, { useState } from "react";
import { useTranslation } from "react-i18next";
import { normalizeLang } from "@/i18n/detector";
import type { Issue } from "@/store/useAppStore";

interface ResumeMakeoverModalProps {
  isOpen: boolean;
  onClose: () => void;
  overallScore: number;
  oneLineVerdict: string;
  issues: Issue[];
  strengths: string[];
}

export default function ResumeMakeoverModal({
  isOpen,
  onClose,
  overallScore,
  oneLineVerdict,
  issues,
  strengths,
}: ResumeMakeoverModalProps) {
  const { i18n } = useTranslation();
  const isHinglish = normalizeLang(i18n.language) === "hi-IN";

  const [copied, setCopied] = useState(false);
  const [downloading, setDownloading] = useState(false);
  const [viewMode, setViewMode] = useState<"split" | "diff">("split");

  if (!isOpen) return null;

  const handleCopyTransformed = async () => {
    const lines = [
      `# ATS-OPTIMIZED RESUME MAKEOVER`,
      `Score Improvement: ${overallScore}/100 -> 88+/100 Target`,
      `Verdict: "${oneLineVerdict}"`,
      ``,
      `## HIGHLIGHTS & CORE STRENGTHS`,
      ...strengths.map((s) => `• ${s}`),
      ``,
      `## TRANSFORMED REVISED BULLET POINTS`,
      ...issues.map((iss, i) => {
        return (
          `[Item #${i + 1}] Category: ${iss.category.toUpperCase()}\n` +
          `• Original: "${iss.quoted_text}"\n` +
          `• Transformed: ${iss.fix}\n`
        );
      }),
      ``,
      `Generated by Resume Roast AI (resumeroast.com)`,
    ];

    try {
      await navigator.clipboard.writeText(lines.join("\n"));
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {}
  };

  const handleDownloadMarkdown = () => {
    setDownloading(true);
    try {
      const markdown = [
        `# ATS-OPTIMIZED REWRITTEN RESUME`,
        `> Generated by Resume Roast (Target Score: 88+ / 100)`,
        `> Original Score: ${overallScore}/100 | Verdict: "${oneLineVerdict}"`,
        ``,
        `## 🎯 KEY TECHNICAL STRENGTHS`,
        ...(strengths || ["Demonstrated engineering capabilities"]).map(
          (s) => `- ${s}`,
        ),
        ``,
        `## 🛠️ REVISED BULLETS & ACTIONABLE IMPACT`,
        ...(issues || []).map((iss, i) => {
          return `### ${i + 1}. [${iss.category.toUpperCase()}] ATS Drop-In Rewrite:\n- **Recommended:** ${iss.fix}\n  *(Replaces: "${iss.quoted_text}")*\n`;
        }),
        ``,
        `---`,
        `Generated with Resume Roast AI (https://resumeroast.com)`,
      ].join("\n");

      const blob = new Blob([markdown], {
        type: "text/markdown;charset=utf-8",
      });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = `Resume-Makeover-Score-${overallScore}-to-88.md`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
    } finally {
      setTimeout(() => setDownloading(false), 1500);
    }
  };

  return (
    <div
      role="dialog"
      aria-modal="true"
      className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-black/85 backdrop-blur-md animate-in fade-in duration-200"
      onClick={onClose}
    >
      <div
        className="w-full max-w-4xl bg-[#14100C] border border-white/[0.12] rounded-sm p-5 sm:p-7 shadow-2xl relative max-h-[92vh] overflow-y-auto text-left"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Close button */}
        <button
          onClick={onClose}
          className="absolute top-4 right-4 text-tan-dim hover:text-paper font-mono text-xl p-1 transition-colors"
          aria-label="Close makeover"
        >
          ✕
        </button>

        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-5 border-b border-white/[0.08] pb-4 pr-8">
          <div>
            <div className="flex items-center gap-2 mb-1">
              <span className="font-mono text-[10px] text-amber-400 font-bold uppercase tracking-widest bg-amber-500/10 border border-amber-500/20 px-2 py-0.5 rounded-sm">
                {isHinglish
                  ? "RESUME MAKEOVER // BEFORE VS AFTER"
                  : "RESUME MAKEOVER // BEFORE VS AFTER"}
              </span>
              <span className="font-mono text-[10px] text-emerald-400 bg-emerald-500/10 border border-emerald-500/20 px-2 py-0.5 rounded-sm">
                Target: 88+/100
              </span>
            </div>
            <h2 className="font-display text-xl sm:text-2xl text-paper">
              {isHinglish
                ? "Flawed Lines vs ATS Drop-In Rewrites 🔄"
                : "Flawed Lines vs ATS Drop-In Rewrites 🔄"}
            </h2>
          </div>

          {/* Action buttons */}
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopyTransformed}
              className="px-3 py-1.5 font-mono text-xs rounded-sm bg-amber-500/20 border border-amber-500/40 text-amber-300 hover:bg-amber-500/30 transition-colors"
            >
              {copied ? "✓ Copied!" : "📋 Copy Makeover"}
            </button>
            <button
              onClick={handleDownloadMarkdown}
              disabled={downloading}
              className="px-3 py-1.5 font-mono text-xs rounded-sm bg-white/[0.05] border border-white/[0.1] text-paper hover:bg-white/[0.1] transition-colors"
            >
              {downloading ? "Saving..." : "⬇️ Download .md"}
            </button>
          </div>
        </div>

        {/* Comparison Header Cards */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-4">
          <div className="bg-red-950/20 border border-red-500/30 rounded-sm p-3 flex items-center justify-between">
            <div className="flex items-center gap-2">
              <span className="text-red-400 font-mono text-xs font-bold uppercase">
                🔴 THE FLAGGED ORIGINAL
              </span>
            </div>
            <span className="font-mono text-xs text-red-300 font-bold bg-red-500/20 px-2 py-0.5 rounded-sm">
              Score: {overallScore}/100
            </span>
          </div>

          <div className="bg-emerald-950/20 border border-emerald-500/30 rounded-sm p-3 flex items-center justify-between">
            <div className="flex items-center gap-2">
              <span className="text-emerald-400 font-mono text-xs font-bold uppercase">
                🟢 THE ATS PRO MAKEOVER
              </span>
            </div>
            <span className="font-mono text-xs text-emerald-300 font-bold bg-emerald-500/20 px-2 py-0.5 rounded-sm">
              Target: 88+/100
            </span>
          </div>
        </div>

        {/* Comparison Rows */}
        <div className="space-y-4">
          {issues.map((iss, idx) => (
            <div
              key={idx}
              className="grid grid-cols-1 md:grid-cols-2 gap-3 bg-black/40 border border-white/[0.06] rounded-sm p-3 sm:p-4 hover:border-white/[0.12] transition-colors"
            >
              {/* Left: Original Flaw */}
              <div className="border-b md:border-b-0 md:border-r border-white/[0.06] pb-3 md:pb-0 md:pr-4 flex flex-col justify-between">
                <div>
                  <div className="flex items-center gap-2 mb-1.5">
                    <span className="font-mono text-[9px] uppercase px-1.5 py-0.2 rounded-xs bg-red-500/20 text-red-300 border border-red-500/30">
                      {iss.category}
                    </span>
                    <span className="font-mono text-[10px] text-tan-dim">
                      Line #{idx + 1}
                    </span>
                  </div>
                  <p className="font-mono text-xs text-red-300/90 line-through decoration-red-500/60 leading-relaxed mb-2">
                    "{iss.quoted_text}"
                  </p>
                </div>
                <div className="bg-black/40 border border-white/[0.04] p-2 rounded-xs">
                  <span className="font-mono text-[10px] text-amber-400 font-bold block mb-0.5">
                    Critique:
                  </span>
                  <p className="font-mono text-[11px] text-tan-dim italic">
                    {iss.roast}
                  </p>
                </div>
              </div>

              {/* Right: Transformed Fix */}
              <div className="md:pl-2 flex flex-col justify-between">
                <div>
                  <div className="flex items-center gap-2 mb-1.5">
                    <span className="font-mono text-[9px] uppercase px-1.5 py-0.2 rounded-xs bg-emerald-500/20 text-emerald-300 border border-emerald-500/30">
                      ATS Optimized Rewrite
                    </span>
                    <span className="font-mono text-[10px] text-emerald-400 font-bold">
                      ✓ STAR Compliant
                    </span>
                  </div>
                  <p className="font-mono text-xs text-emerald-200 leading-relaxed font-medium mb-2">
                    {iss.fix}
                  </p>
                </div>
                <div className="flex items-center justify-between pt-1">
                  <span className="font-mono text-[10px] text-tan-dim">
                    Drop-in ready for PDF/Docx
                  </span>
                  <button
                    onClick={async () => {
                      try {
                        await navigator.clipboard.writeText(iss.fix);
                      } catch {}
                    }}
                    className="font-mono text-[10px] text-amber-300 hover:text-amber-200 border border-amber-500/20 bg-amber-500/10 px-2 py-0.5 rounded-sm transition-colors"
                  >
                    Copy Line
                  </button>
                </div>
              </div>
            </div>
          ))}
        </div>

        {/* Footer */}
        <div className="mt-6 pt-4 border-t border-white/[0.08] flex items-center justify-between font-mono text-[11px] text-tan-dim">
          <span>
            Substitute these lines into your resume to immediately leap from{" "}
            {overallScore} to 88+
          </span>
          <button
            onClick={onClose}
            className="text-tan hover:text-paper underline"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
}
